#!/usr/bin/env python3
"""Expose bundled model presentation strings to the standard gettext extraction."""
import argparse
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "eeschema/circuitalive/model_strings.h"
DIAGNOSTICS = ROOT / "eeschema/circuitalive/diagnostic_strings.h"


def collect(value, strings):
    if isinstance(value, dict):
        for key, child in value.items():
            if key in ("name", "description", "label", "family", "role") and isinstance(child, str):
                if child:
                    strings.add(child)
            elif key == "category" and isinstance(child, str):
                strings.update(filter(None, child.split("/")))
            elif key == "equations":
                strings.update(child)
            elif key not in ("authoring", "spice", "behavioral"):
                collect(child, strings)
    elif isinstance(value, list):
        for child in value:
            collect(child, strings)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    strings = {"Internal operations:", "Custom", "Custom 555 timer",
               "555 assembled visually from divider, comparators, reset-priority latch, output and discharge blocks."}
    for model in sorted((ROOT / "simulation").rglob("*.casim")):
        collect(json.loads(model.read_text()), strings)
    content = ("/* Generated by tools/circuitalive/update-model-translations.py.\n"
               " * Gettext extraction only; original model files remain language independent. */\n"
               "#if 0\n")
    content += "".join("wxTRANSLATE( " + json.dumps(s, ensure_ascii=False) + " );\n" for s in sorted(strings))
    content += "#endif\n"
    diagnostics = {"Overcurrent: ", "Logic supply out of range: "}
    sources = list((ROOT / "eeschema/circuitalive").glob("*.cpp"))
    sources += [ROOT / "eeschema/sim" / name for name in
                ("interactive_sim_session.cpp", "interactive_sim_worker.cpp", "memory_image.cpp", "runtime_memory.cpp", "programmable_runtime.cpp")]
    for source in sources:
        for expression in re.finditer(
                r'(?:throw std::(?:runtime_error|invalid_argument)|(?:m_error|message)\s*=)\s*([^;]+);', source.read_text()):
            for literal in re.findall(r'"(?:[^"\\]|\\.)*"', expression[1]):
                text = ast.literal_eval(literal)
                if len(text) > 5 and re.search(r'[a-z] [a-z]', text):
                    diagnostics.add(text)
    diagnostic_content = ("/* Generated by tools/circuitalive/update-model-translations.py. */\n"
                          "#pragma once\n#include <wx/intl.h>\nnamespace CIRCUITALIVE\n{\n"
                          "inline const char* const DIAGNOSTIC_STRINGS[] = {\n")
    # Longer fragments win when diagnostic messages contain technical payloads.
    diagnostic_content += "".join("    wxTRANSLATE( " + json.dumps(s, ensure_ascii=False) + " ),\n"
                                  for s in sorted(diagnostics, key=lambda s: (-len(s), s)))
    diagnostic_content += "};\n}\n"
    for target, generated in ((TARGET, content), (DIAGNOSTICS, diagnostic_content)):
        if args.check:
            if not target.exists() or target.read_text() != generated:
                raise SystemExit("Translation strings are stale; run " + str(Path(__file__).relative_to(ROOT)))
        else:
            target.write_text(generated)


if __name__ == "__main__":
    main()
