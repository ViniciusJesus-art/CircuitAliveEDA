#!/usr/bin/env python3
"""Reproducibly bundle the vendored MIT modules; no npm/Node build dependency."""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = ROOT / "thirdparty/avr8js/cjs"


def coalesced_timers(text):
    """Schedule counter observations (compare/overflow/turn), not every tick.

    TCNT reads still synchronize on demand. Writes invalidate the deadline.
    Phase PWM skips only intervals without a compare, bottom or top event.
    """
    text = text.replace('this.lastCycle + newDivider - cpu.cycles',
                        'this.lastCycle + this.nextEventTicks() * newDivider - cpu.cycles')
    text = text.replace('this.lastCycle + divider - cpu.cycles',
                        'this.lastCycle + this.nextEventTicks() * divider - cpu.cycles')
    marker = '    phasePwmCount(value, delta) {'
    method = '''    nextEventTicks() {
        const value=this.tcnt, top=this.TOP;
        const phase=this.timerMode===PWMPhaseCorrect || this.timerMode===PWMPhaseFrequencyCorrect;
        let distance=phase ? (this.countingUp ? top-value : value) : top+1-value;
        if(distance<1)return 1;
        for(const compare of [this.ocrA,this.ocrB,...(this.hasOCRC?[this.ocrC]:[])]) {
            const d=phase && !this.countingUp ? value-compare : compare-value;
            if(d>0 && compare<=top && d<distance)distance=d;
        }
        return distance;
    }
'''
    assert marker in text
    text = text.replace(marker, method + marker)
    marker = '        while (delta > 0) {\n'
    assert text.count(marker) == 1
    text = text.replace(marker, marker + '''            // Skip only ticks with no observable timer event.
            let distance=this.countingUp ? TOP-value : value;
            for(const compare of [ocrA,ocrB,...(hasOCRC?[ocrC]:[])]) {
                const d=this.countingUp ? compare-value : value-compare;
                if(d>0 && compare<=TOP && d<distance)distance=d;
            }
            const skip=Math.min(delta,Math.max(0,distance-1));
            if(skip) { value+=this.countingUp ? skip : -skip;delta-=skip; }
            if(!delta)break;
''')
    # Changing a compare/mode can move the next event earlier. Synchronize the
    # existing counter first, then reevaluate at the next instruction boundary.
    for register in ['config.OCRA','config.OCRB','config.OCRC','config.ICR','config.TCCRA']:
        marker = 'this.cpu.writeHooks[' + register + '] = (value) => {\n'
        if register == 'config.TCCRA': marker = 'cpu.writeHooks[config.TCCRA] = (value) => {\n'
        assert marker in text
        text = text.replace(marker, marker + '''            this.count(false);
            if(this.divider)this.cpu.updateClockEvent(this.count,0);
''')
    return text


def indexed_instructions(text):
    """Keep upstream instruction bodies, selecting them with a generated LUT.

    An interpreter otherwise evaluates up to 99 opcode masks per instruction.
    Resolve those constant masks once at build time, in upstream priority order.
    """
    start = text.index("function avrInstruction(cpu) {")
    marker = "    cpu.pc = (cpu.pc + 1) % cpu.progMem.length;"
    end = text.index(marker, start)
    ladder = text[start:end]
    arms = re.findall(r"^    (?:else )?if \((.*?)\) \{\n(.*?)^    \}\n",
                      ladder, re.MULTILINE | re.DOTALL)
    assert len(arms) == 99, "Revalidate upstream decoder before updating AVR8js"
    expected = "function avrInstruction(cpu) {\n    const opcode = cpu.progMem[cpu.pc];\n"
    for index, (condition, body) in enumerate(arms):
        expected += "    " + ("else " if index else "") + "if (" + condition + ") {\n" + body + "    }\n"
    assert expected == ladder, "Instruction extraction must preserve every upstream branch"
    # A bounded native execution path shares these exact MIT instruction bodies.
    # Peripheral I/O and clock/interrupt boundaries stay with the JS backend.
    native = ['// Generated by simulation/runtime/build-avr8js.py.\n',
              '// AVR8js 0.21.1, MIT; see thirdparty/avr8js/LICENSE.\n']
    for index, (condition, body) in enumerate(arms):
        condition = condition.replace('===', '==').replace('!==', '!=')
        body = body.replace('const { pc22Bits } = cpu;', 'const pc22Bits = cpu.pc22Bits;')
        body = re.sub(r'\bconst\b', 'const auto', body)
        body = re.sub(r'\blet\b', 'auto', body)
        body = body.replace('===', '==').replace('!==', '!=').replace('>>>', '>>')
        native.append(('if' if not index else 'else if') + ' (' + condition + ') {\n' + body + '}\n')
    native.append('else { return false; }\n')
    (ROOT / 'eeschema/sim/avr_instruction.inc').write_text(''.join(native))
    conditions = []
    for condition, _ in arms:
        assert re.fullmatch(r"[\s()&|=!<>0-9a-fxopcode]+", condition), condition
        expression = condition.replace("===", "==").replace("!==", "!=").replace("&&", " and ").replace("||", " or ")
        conditions.append(compile(" ".join(expression.split()), "opcode-mask", "eval"))
    table = []
    for opcode in range(65536):
        table.append(next((i + 1 for i, condition in enumerate(conditions)
                           if eval(condition, {"__builtins__": {}}, {"opcode": opcode})), 0))
    result = text[:start]
    result += "// Generated opcode dispatch; instruction bodies below remain upstream code.\n"
    result += "const instructionHandlers = [function(cpu, opcode) {\n"
    result += "throw new Error('Unsupported AVR opcode 0x' + opcode.toString(16) + ' at byte ' + (cpu.pc * 2));\n}"
    for _, body in arms:
        result += ",\nfunction(cpu, opcode) {\n" + body + "}"
    result += "];\nconst instructionMapHex =\n"
    encoded = bytes(table).hex()
    result += " +\n".join(repr(encoded[i:i + 256]) for i in range(0, len(encoded), 256)) + ";\n"
    result += "const instructionMap = new Uint8Array(65536);\n"
    result += "for (let i=0; i<65536; i++) instructionMap[i] = parseInt(instructionMapHex.slice(i*2,i*2+2),16);\n"
    result += "function avrInstruction(cpu) {\nconst opcode = cpu.progMem[cpu.pc];\n"
    result += "instructionHandlers[instructionMap[opcode]](cpu, opcode);\n"
    return result + text[end:]


parts = ["// AVR8js 0.21.1, MIT (thirdparty/avr8js/LICENSE). Generated by build-avr8js.py.\n",
         "(function(global){'use strict';const modules=Object.create(null),cache=Object.create(null);\n"]
for path in sorted(SOURCE.rglob("*.js")):
    module = path.relative_to(SOURCE).with_suffix("").as_posix()
    parts.append("modules[" + repr(module) + "]=function(require,module,exports){\n")
    text = path.read_text()
    if module == "cpu/instruction":
        text = indexed_instructions(text)
    if module == "peripherals/timer":
        text = coalesced_timers(text)
    parts.append(text)
    parts.append("\n};\n")
parts.append("""
function load(id){
  if(cache[id])return cache[id].exports;
  if(!modules[id])throw new Error('Unknown bundled AVR module: '+id);
  const module={exports:{}};cache[id]=module;
  function require(path){
    const base=id.split('/');base.pop();
    for(const part of path.split('/')){
      if(part==='..')base.pop();else if(part!=='.')base.push(part);
    }
    return load(base.join('/'));
  }
  modules[id](require,module,module.exports);return module.exports;
}
global.AVR8js=load('index');
})(globalThis);
""")
parts.append((HERE / "avr8js-adapter.js").read_text())
(HERE / "avr8js.js").write_text("".join(parts))
